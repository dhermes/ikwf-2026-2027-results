def main() -> None:
    session = requests.Session()
    roster_directory = _ROOT / "_raw-data" / "ikwf-rosters"
    total = len(_CLUB_IDS)

    for i, club_id in enumerate(_CLUB_IDS):
        filename = roster_directory / f"{club_id}.html"
        if os.path.exists(filename):
            continue

        url = (
            f"https://www.ikwf.org/showClub.php?cStatus=1&"
            f"club_id={club_id}&submit=View+Roster"
        )
        response = session.get(
            url, headers={"User-Agent": "Mozilla/5.0"}, allow_redirects=False
        )
        if response.status_code != 200:
            raise NotImplementedError(response.status_code)

        content = response.content
        with open(filename, "wb") as file_obj:
            file_obj.write(content)

        print(f"Done with {club_id} ({i + 1} / {total})")


if __name__ == "__main__":
    main()
